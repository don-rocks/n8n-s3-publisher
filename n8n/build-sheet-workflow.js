// build-sheet-workflow.js
// Generates n8n/workflows/publish-from-sheet.json: reads "Ready" rows from the
// content calendar, publishes each due post, and writes the result back to its row.
// Usage: node n8n/build-sheet-workflow.js   (needs terraform outputs; see n8n/sheet.json)
'use strict';

const {
  terraformOutputs, readRepoFile, renderFunctions, node, connect, writeWorkflow,
  invalidateNode, liveCheckNodes,
} = require('./lib/build-common');

const tf = terraformOutputs();
const sheet = JSON.parse(readRepoFile('n8n/sheet.json'));
const settings = {
  bucket: tf.bucket,
  distributionId: tf.distributionId,
  site: { url: tf.siteUrl, name: sheet.siteName, lang: sheet.lang },
};

const sheetRef = {
  authentication: 'serviceAccount',
  resource: 'sheet',
  documentId: { __rl: true, mode: 'id', value: sheet.spreadsheetId },
  sheetName: { __rl: true, mode: 'id', value: String(sheet.sheetGid) },
};

// Turns each sheet row into a rendered page, or an error for that row.
const buildCode = `// Turns each "Ready" row into a finished page (binary) or an error for that row.
// Generated by n8n/build-sheet-workflow.js from templates/; edit those, not this.
const TEMPLATE = ${JSON.stringify(readRepoFile('templates/post.html'))};
const SETTINGS = ${JSON.stringify(settings, null, 2)};

${renderFunctions()}
const today = $now.toFormat('yyyy-MM-dd');

function cell(row, key) {
  const v = row[key];
  return v === undefined || v === null ? '' : String(v).trim();
}

// Accepts YYYY-MM-DD, YYYY/MM/DD, or a Sheets date serial number.
function isoDate(raw) {
  const v = raw === undefined || raw === null ? '' : String(raw).trim();
  if (v === '') return '';
  if (/^\\d{4}-\\d{2}-\\d{2}$/.test(v)) return v;
  if (/^\\d{4}\\/\\d{2}\\/\\d{2}$/.test(v)) return v.replace(/\\//g, '-');
  if (/^\\d+(\\.\\d+)?$/.test(v)) {
    return new Date(Date.UTC(1899, 11, 30) + Math.floor(Number(v)) * 86400000).toISOString().slice(0, 10);
  }
  return null;
}

const out = [];
$input.all().forEach((item, i) => {
  const row = item.json;
  const base = { row_number: row.row_number, slug: cell(row, 'slug') };
  try {
    const date = isoDate(row.publish_date);
    if (date === null) throw new Error(\`publish_date "\${row.publish_date}" must be YYYY-MM-DD (format the column as yyyy-mm-dd)\`);
    if (date === '') throw new Error('publish_date is required');
    if (date > today) return; // Not due yet: leave the row as Ready.

    const sections = [];
    for (let n = 1; n <= 5; n++) {
      const q = cell(row, 'q' + n), a = cell(row, 'a' + n);
      if (q || a) sections.push({ question: q, answer: a });
    }
    const faq = [];
    for (let n = 1; n <= 3; n++) {
      const q = cell(row, 'faq_q' + n), a = cell(row, 'faq_a' + n);
      if (q || a) faq.push({ question: q, answer: a });
    }
    const post = {
      slug: cell(row, 'slug'),
      title: cell(row, 'title'),
      description: cell(row, 'description'),
      author: cell(row, 'author'),
      date_published: date,
      date_modified: date,
      og_image: cell(row, 'og_image'),
      intro: cell(row, 'intro'),
      takeaways: cell(row, 'takeaways').split(/\\r?\\n/).map((t) => t.trim()).filter(Boolean),
      sections,
      faq,
    };
    const html = render(TEMPLATE, post, SETTINGS.site);
    out.push({
      json: {
        ok: true, ...base,
        title: post.title,
        key: \`posts/\${post.slug}/index.html\`,
        url: \`\${SETTINGS.site.url}/posts/\${post.slug}/\`,
        bucket: SETTINGS.bucket,
        distributionId: SETTINGS.distributionId,
        bytes: Buffer.byteLength(html, 'utf8'),
      },
      // The S3 node uses this mimeType as the object's Content-Type.
      binary: {
        data: {
          data: Buffer.from(html, 'utf8').toString('base64'),
          mimeType: 'text/html; charset=utf-8',
          fileName: 'index.html',
          fileExtension: 'html',
        },
      },
      pairedItem: { item: i },
    });
  } catch (err) {
    out.push({ json: { ok: false, ...base, error: err.message.replace(/:\\n- /, ': ').replace(/\\n- /g, '; ').replace(/\\n/g, ' ') }, pairedItem: { item: i } });
  }
});
return out;
`;

const B = "$('Build pages').item.json";

const nodes = [
  node('Start', 'n8n-nodes-base.manualTrigger', 1, [0, 200], {}),
  node('Every morning', 'n8n-nodes-base.scheduleTrigger', 1.2, [0, 400], {
    rule: { interval: [{ triggerAtHour: 7 }] },
  }),
  node('Read Ready rows', 'n8n-nodes-base.googleSheets', 4.5, [220, 300], {
    ...sheetRef,
    operation: 'read',
    filtersUI: { values: [{ lookupColumn: 'status', lookupValue: 'Ready' }] },
    options: {},
  }),
  node('Build pages', 'n8n-nodes-base.code', 2, [440, 300], { jsCode: buildCode }),
  node('Valid?', 'n8n-nodes-base.if', 2.2, [660, 300], {
    conditions: {
      options: { caseSensitive: true, leftValue: '', typeValidation: 'loose', version: 2 },
      conditions: [{ id: 'ok', leftValue: '={{ $json.ok }}', rightValue: '',
        operator: { type: 'boolean', operation: 'true', singleValue: true } }],
      combinator: 'and',
    },
    options: {},
  }),
  node('Upload to S3', 'n8n-nodes-base.awsS3', 2, [880, 200], {
    resource: 'file',
    operation: 'upload',
    bucketName: '={{ $json.bucket }}',
    fileName: '={{ $json.key }}',
    binaryData: true,
    binaryPropertyName: 'data',
    additionalFields: {},
  }),
  invalidateNode('Invalidate cache', [1100, 200], `${B}.slug`, `${B}.distributionId`),
  node('Wait for cache', 'n8n-nodes-base.wait', 1.1, [1320, 200], { amount: 20, unit: 'seconds' },
    { webhookId: 'publish-from-sheet-wait' }),
  ...liveCheckNodes('Check live page', 'Is it live?', 1540, `${B}.url`),
  node('Mark published', 'n8n-nodes-base.code', 2, [1980, 100], {
    mode: 'runOnceForEachItem',
    jsCode: `const p = ${B};\nreturn { json: { row_number: p.row_number, status: 'Published', published_at: $now.toFormat('yyyy-MM-dd HH:mm'), url: p.url, error: '' } };\n`,
  }),
  node('Mark not live', 'n8n-nodes-base.code', 2, [1980, 300], {
    mode: 'runOnceForEachItem',
    jsCode: `const p = ${B};\nreturn { json: { row_number: p.row_number, status: 'Error', error: \`Uploaded, but the live page check failed (HTTP \${$json.statusCode})\` } };\n`,
  }),
  node('Mark invalid', 'n8n-nodes-base.code', 2, [880, 450], {
    mode: 'runOnceForEachItem',
    jsCode: "return { json: { row_number: $json.row_number, status: 'Error', error: $json.error } };\n",
  }),
  node('Update sheet row', 'n8n-nodes-base.googleSheets', 4.5, [2200, 300], {
    ...sheetRef,
    operation: 'update',
    columns: { mappingMode: 'autoMapInputData', value: {}, matchingColumns: ['row_number'], schema: [] },
    options: { handlingExtraData: 'ignoreIt' },
  }),
];
// Fix the live-check positions to the top lane.
nodes.find((n) => n.name === 'Check live page').position = [1540, 200];
nodes.find((n) => n.name === 'Is it live?').position = [1760, 200];

const c = {};
connect(c, 'Start', 'Read Ready rows');
connect(c, 'Every morning', 'Read Ready rows');
connect(c, 'Read Ready rows', 'Build pages');
connect(c, 'Build pages', 'Valid?');
connect(c, 'Valid?', 'Upload to S3', 0);
connect(c, 'Valid?', 'Mark invalid', 1);
connect(c, 'Upload to S3', 'Invalidate cache');
connect(c, 'Invalidate cache', 'Wait for cache');
connect(c, 'Wait for cache', 'Check live page');
connect(c, 'Check live page', 'Is it live?');
connect(c, 'Is it live?', 'Mark published', 0);
connect(c, 'Is it live?', 'Mark not live', 1);
connect(c, 'Mark published', 'Update sheet row');
connect(c, 'Mark not live', 'Update sheet row');
connect(c, 'Mark invalid', 'Update sheet row');

writeWorkflow('publish-from-sheet.json', {
  name: 'Publish from sheet',
  nodes,
  connections: c,
  settings: { executionOrder: 'v1', timezone: 'Africa/Johannesburg' },
  pinData: {},
});
